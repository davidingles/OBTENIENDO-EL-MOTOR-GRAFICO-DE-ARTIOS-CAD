const fs = require('node:fs');
const path = require('node:path');
const engine = require('../dieline-engine');
const root = path.resolve(__dirname, '..');
const source = path.resolve(process.argv[2] || path.join(root, '../Banco de Troqueles/bandejas automontables'));
const models = fs.readdirSync(source).filter(name => /\.svg$/i.test(name)).sort().map(filename => {
  const match = /^bandeja_(C[1358]|cartoncillo)_(\d+)_(\d+)x(\d+)mm(?:_(.*))?\.svg$/i.exec(filename);
  if (!match) throw new Error('Nombre de troquel desconocido: ' + filename);
  const [, boardCode, number, width, height, detail] = match;
  const svgText = fs.readFileSync(path.join(source, filename), 'utf8');
  const geometry = engine.buildDielineModel(svgText);
  if (!geometry.faces.length) throw new Error('Troquel sin paneles: ' + filename);
  const boardIndex = ['C1', 'C3', 'C5', 'C8', 'cartoncillo'].indexOf(boardCode);
  return {num: 900000000000 + boardIndex * 1000 + Number(number), bundledModel: true,
    name: `Bandeja ${boardCode} ${number}${detail ? ' · ' + detail.replaceAll('_', ' ') : ''}`,
    boardCode, sourceFilename: filename, flatWidth: Number(width), flatHeight: Number(height),
    modelCategories: ['automount-trays', 'tray-box-dielines'], useCategories: [], svgText};
});
fs.writeFileSync(path.join(root, 'assets/automount-trays.js'),
  '// Generated by scripts/import-automount-trays.js from the local SVG bank.\n' +
  'window.AUTOMOUNT_TRAYS = ' + JSON.stringify(models) + ';\n' +
  `for (const item of window.AUTOMOUNT_TRAYS) {
  let geometry;
  Object.defineProperty(item, 'geometry', {get() {
    return geometry || (geometry = DielineEngine.buildDielineModel(item.svgText));
  }});
}
`);
console.log(`Incorporados ${models.length} troqueles automontables.`);
